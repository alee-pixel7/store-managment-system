// ============================================================
// fix-recalc-mismatch.js
// One-time (idempotent) repair: heal items where current_stock
// disagrees with the transaction-based recalculation.
//
// For each mismatch it creates ONE signed ADJUST transaction with
// the difference — displayed stock is NEVER modified directly;
// recalculateStock() lands on the displayed value.
//
// Usage:  node src/scripts/fix-recalc-mismatch.js [--dry-run]
// ============================================================

const { PrismaClient } = require('@prisma/client');
const prisma = new PrismaClient();

const DRY = process.argv.includes('--dry-run');

function recalcFromRows(rows) {
  let stock = 0;
  for (const ti of rows) {
    if (ti.transaction.is_reversed) continue;
    // IN/RETURN add, OUT subtract, ADJUST/REVERSAL signed
    if (ti.transaction.txn_type === 'OUT') stock -= ti.quantity;
    else stock += ti.quantity;
  }
  return stock;
}

async function generateTxnNo(client, txnType, year) {
  const last = await client.transactions.findFirst({
    where: {
      txn_type: txnType,
      txn_date: { gte: new Date(`${year}-01-01`), lt: new Date(`${year + 1}-01-01`) },
    },
    orderBy: { txn_no: 'desc' },
  });
  let n = 1;
  if (last) {
    const parts = last.txn_no.split('-');
    n = parseInt(parts[parts.length - 1], 10) + 1;
  }
  return `${txnType}-${year}-${String(n).padStart(4, '0')}`;
}

async function main() {
  console.log(`\n🔍 Scanning items for current_stock vs recalc mismatches${DRY ? ' (DRY RUN)' : ''}...`);

  const items = await prisma.items.findMany({
    where: { is_active: true },
    select: { id: true, item_code: true, item_name: true, current_stock: true },
  });
  console.log(`  Active items: ${items.length}`);

  const txnRows = await prisma.transaction_items.findMany({
    select: {
      item_id: true,
      quantity: true,
      transaction: { select: { txn_type: true, is_reversed: true } },
    },
  });

  const byItem = new Map();
  for (const row of txnRows) {
    if (!byItem.has(row.item_id)) byItem.set(row.item_id, []);
    byItem.get(row.item_id).push(row);
  }

  const mismatches = [];
  for (const item of items) {
    const rows = byItem.get(item.id) || [];
    const recalc = recalcFromRows(rows);
    const diff = item.current_stock - recalc;
    if (Math.abs(diff) > 1e-9) {
      mismatches.push({ ...item, recalc, diff });
    }
  }

  console.log(`  ❌ Mismatches: ${mismatches.length}`);
  if (mismatches.length === 0) {
    console.log('✅ Nothing to fix — displayed stock matches the ledger everywhere.');
    return;
  }

  for (const m of mismatches.slice(0, 20)) {
    console.log(`     ${m.item_code} "${m.item_name}": displayed=${m.current_stock} recalc=${m.recalc} diff=${m.diff}`);
  }
  if (mismatches.length > 20) console.log(`     ... and ${mismatches.length - 20} more`);

  if (DRY) {
    console.log('\n🏁 Dry run — no changes written.');
    return;
  }

  // Group mismatches by item — one ADJUST per item
  const year = new Date().getFullYear();
  let created = 0;

  for (const m of mismatches) {
    await prisma.$transaction(async (tx) => {
      const txnNo = await generateTxnNo(tx, 'ADJUST', year);
      const txn = await tx.transactions.create({
        data: {
          txn_no: txnNo,
          txn_type: 'ADJUST',
          txn_date: new Date(),
          purpose: 'Ledger reconciliation',
          remarks: `fix-recalc-mismatch: displayed=${m.current_stock}, recalc=${m.recalc}, delta=${m.diff} (${m.item_code})`,
          created_by: await getSystemUserId(tx),
        },
      });
      await tx.transaction_items.create({
        data: {
          transaction_id: txn.id,
          item_id: m.id,
          quantity: m.diff,
          rate: 0,
          line_remarks: 'Auto-generated by fix-recalc-mismatch.js',
        },
      });
      // Do NOT touch current_stock — recalc must land on displayed value
    });
    created++;
  }

  console.log(`\n🔧 Created ${created} ADJUST transactions.`);

  // ===== Self-verify: mismatch count must be 0 =====
  const itemsAfter = await prisma.items.findMany({
    where: { is_active: true },
    select: { id: true, item_code: true, current_stock: true },
  });
  const rowsAfter = await prisma.transaction_items.findMany({
    select: {
      item_id: true,
      quantity: true,
      transaction: { select: { txn_type: true, is_reversed: true } },
    },
  });
  const byItemAfter = new Map();
  for (const row of rowsAfter) {
    if (!byItemAfter.has(row.item_id)) byItemAfter.set(row.item_id, []);
    byItemAfter.get(row.item_id).push(row);
  }
  let stillBad = 0;
  for (const item of itemsAfter) {
    const recalc = recalcFromRows(byItemAfter.get(item.id) || []);
    if (Math.abs(item.current_stock - recalc) > 1e-9) {
      stillBad++;
      console.log(`   ⚠️ still mismatched: ${item.item_code} displayed=${item.current_stock} recalc=${recalc}`);
    }
  }

  if (stillBad === 0) {
    console.log('✅ Self-verify PASSED: mismatch = 0');
  } else {
    console.error(`❌ Self-verify FAILED: ${stillBad} mismatches remain`);
    process.exit(1);
  }
}

// The system/admin user owns auto-generated adjustments
async function getSystemUserId(tx) {
  const admin = await tx.users.findFirst({
    where: { role: 'ADMIN' },
    orderBy: { id: 'asc' },
    select: { id: true },
  });
  if (admin) return admin.id;
  const any = await tx.users.findFirst({ orderBy: { id: 'asc' }, select: { id: true } });
  if (!any) throw new Error('No users in database — run `npx prisma db seed` first');
  return any.id;
}

main()
  .catch((e) => {
    console.error('❌', e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
